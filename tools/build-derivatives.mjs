/**
 * Generates the display-size images the atlas pages actually use.
 *
 * The masters are full scan resolution (2765x3960 and up, 2-4 MB each) but the
 * compare slider is at most ~700 CSS px wide, so shipping masters to the slider
 * wastes ~90% of every byte. This writes a 1400px-long-edge WebP next to each
 * master - 1400 covers a 700px slider at 2x DPR - and the masters are then only
 * fetched by the lightbox, on an explicit user action.
 *
 * Re-runs are incremental: a derivative newer than its master is left alone.
 *
 * Usage: npm run derivatives [-- --force]
 */
import sharp from 'sharp';
import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const MAPS = path.join(ROOT, 'maps');
const ASSETS = path.join(ROOT, 'assets');

const LONG_EDGE = 1400;
const WEBP_QUALITY = 82;
const FORCE = process.argv.includes('--force');

/**
 * Narrow tier for srcset. The compare slider is ~700 CSS px at most on desktop
 * (measured 696-699) and ~334 px on a phone, so a 1x display was being sent an
 * image about twice as wide as it could show.
 *
 * This is generated BY WIDTH, unlike the large tier which fits inside a
 * LONG_EDGE box - srcset descriptors are widths, and a portrait map fitted to a
 * 1400 box is only ~984 px wide. Adding a narrow tier rather than regenerating
 * the large one by width keeps high-DPR visitors on exactly the bytes they get
 * today instead of increasing them.
 */
const NARROW_WIDTH = 700;

/**
 * Master basenames we derive from, read from the manifest's rendition config so
 * adding a new art pass is a config change rather than a code change. A map
 * that does not yet have a given rendition is simply skipped, which lets a new
 * pass roll out one map at a time.
 */
const manifest = JSON.parse(
  await fs.readFile(path.join(ROOT, 'data', 'maps.json'), 'utf8')
);
const KINDS = manifest.renditions.map((r) => r.basename);

/** The map whose remaster becomes the social card. */
const SOCIAL_CARD_SOURCE = 'continent-1/stormwind-district';

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
const mb = (n) => `${(n / 1024 / 1024).toFixed(2)} MB`;

async function exists(p) {
  try { await fs.access(p); return true; } catch { return false; }
}

/** Find every map directory: maps/continent-N/slug. */
async function findMapDirs() {
  const out = [];
  for (const continent of await fs.readdir(MAPS, { withFileTypes: true })) {
    if (!continent.isDirectory() || !continent.name.startsWith('continent-')) continue;
    const cDir = path.join(MAPS, continent.name);
    for (const slug of await fs.readdir(cDir, { withFileTypes: true })) {
      if (!slug.isDirectory()) continue;
      out.push({ rel: `${continent.name}/${slug.name}`, dir: path.join(cDir, slug.name) });
    }
  }
  return out.sort((a, b) => a.rel.localeCompare(b.rel));
}

/** Locate the master file for a kind, whatever its extension. */
async function findMaster(dir, kind) {
  const entries = await fs.readdir(dir);
  // Never treat an already-generated display-*.webp as a master.
  const match = entries.find((f) => {
    const base = path.basename(f, path.extname(f));
    return base === kind;
  });
  return match ? path.join(dir, match) : null;
}

async function isStale(src, dest) {
  if (FORCE || !(await exists(dest))) return true;
  const [s, d] = await Promise.all([fs.stat(src), fs.stat(dest)]);
  return s.mtimeMs > d.mtimeMs;
}

async function main() {
  const dirs = await findMapDirs();
  if (!dirs.length) {
    console.error('No maps/continent-*/<slug> directories found.');
    process.exit(1);
  }

  let masterBytes = 0;
  let displayBytes = 0;
  let narrowTierBytes = 0;
  let written = 0;
  let skipped = 0;
  const rows = [];
  const missing = [];

  for (const { rel, dir } of dirs) {
    for (const kind of KINDS) {
      const src = await findMaster(dir, kind);
      if (!src) {
        // Expected while a new rendition is only part-way rolled out.
        missing.push(`${rel}/${kind}`);
        continue;
      }
      const dest = path.join(dir, `display-${kind}.webp`);
      const narrowDest = path.join(dir, `display-${kind}-${NARROW_WIDTH}.webp`);
      const srcSize = (await fs.stat(src)).size;
      masterBytes += srcSize;

      if (await isStale(src, dest)) {
        await sharp(src)
          .resize({
            width: LONG_EDGE,
            height: LONG_EDGE,
            fit: 'inside',
            withoutEnlargement: true,
          })
          .webp({ quality: WEBP_QUALITY })
          .toFile(dest);
        written++;
      } else {
        skipped++;
      }

      if (await isStale(src, narrowDest)) {
        await sharp(src)
          .resize({ width: NARROW_WIDTH, withoutEnlargement: true })
          .webp({ quality: WEBP_QUALITY })
          .toFile(narrowDest);
        written++;
      } else {
        skipped++;
      }

      const destSize = (await fs.stat(dest)).size;
      const narrowSize = (await fs.stat(narrowDest)).size;
      displayBytes += destSize;
      narrowTierBytes += narrowSize;
      const meta = await sharp(dest).metadata();
      const narrowMeta = await sharp(narrowDest).metadata();
      rows.push({
        map: rel,
        kind,
        dims: `${meta.width}x${meta.height}`,
        narrowDims: `${narrowMeta.width}x${narrowMeta.height}`,
        master: srcSize,
        display: destSize,
        narrow: narrowSize,
        cut: 1 - destSize / srcSize,
      });
    }
  }

  // Social card for og:image.
  await fs.mkdir(ASSETS, { recursive: true });
  const cardSrc = await findMaster(path.join(MAPS, SOCIAL_CARD_SOURCE), 'remaster');
  const cardDest = path.join(ASSETS, 'social-card.jpg');
  if (cardSrc && (await isStale(cardSrc, cardDest))) {
    await sharp(cardSrc)
      .resize({ width: 1200, height: 630, fit: 'cover', position: 'top' })
      .jpeg({ quality: 82, mozjpeg: true })
      .toFile(cardDest);
    console.log(`social card -> assets/social-card.jpg (1200x630, ${kb((await fs.stat(cardDest)).size)})`);
  }

  console.log('');
  console.log(`  ${'map'.padEnd(34)} ${'kind'.padEnd(9)} ${'large'.padEnd(24)} narrow (700w tier)`);
  for (const r of rows) {
    console.log(
      `  ${r.map.padEnd(34)} ${r.kind.padEnd(9)} ` +
      `${(r.dims + ' ' + kb(r.display)).padEnd(24)} ${r.narrowDims} ${kb(r.narrow)}`
    );
  }

  if (missing.length) {
    const byKind = {};
    for (const m of missing) {
      const k = m.split('/').pop();
      (byKind[k] ??= []).push(m.split('/').slice(0, -1).join('/'));
    }
    console.log('');
    for (const [kind, maps] of Object.entries(byKind)) {
      console.log(`  not yet present: ${kind} on ${maps.length} map(s) - rendition still rolling out`);
    }
  }

  console.log('');
  console.log(`  derivatives written: ${written}   up to date: ${skipped}`);
  console.log(`  masters total:      ${mb(masterBytes)}   (viewer only, never on page load)`);
  console.log('');
  console.log(`  What a full scroll actually transfers, by display:`);
  console.log(`    1x display  -> narrow tier: ${mb(narrowTierBytes)}`);
  console.log(`    2x / 3x     -> large tier:  ${mb(displayBytes)}`);
  console.log(`    narrow tier is ${((1 - narrowTierBytes / displayBytes) * 100).toFixed(0)}% lighter than the large one`);
  const perMonth = (n) => Math.round((100 * 1024 ** 3) / n).toLocaleString('en-GB');
  console.log('');
  console.log(`  Full-scroll views per month before the 100 GB Pages soft limit:`);
  console.log(`    1x visitors: ~${perMonth(narrowTierBytes)}    high-DPR visitors: ~${perMonth(displayBytes)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
